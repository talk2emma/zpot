#!/usr/bin/env node
/* Generates src/constants/env.generated.ts from mobile/.env (or defaults). Public values only. */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const envFile = fs.existsSync(path.join(root, '.env')) ? path.join(root, '.env') : path.join(root, '.env.example');
const vars = {};
for (const line of fs.readFileSync(envFile, 'utf8').split('\n')) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) vars[m[1]] = m[2].replace(/^["']|["']$/g, '');
}
const forbidden = Object.entries(vars).filter(([, v]) => /^sk\./.test(v));
if (forbidden.length) {
  console.error('Refusing to embed secret Mapbox tokens (sk.*) in the app bundle:', forbidden.map(([k]) => k).join(', '));
  process.exit(1);
}
const keys = ['ZPOT_API_URL_ANDROID', 'ZPOT_API_URL_IOS', 'ZPOT_MAP_PROVIDER', 'ZPOT_MAP_STYLE_URL',
  'ZPOT_MAPBOX_PUBLIC_TOKEN', 'ZPOT_REQUEST_TIMEOUT_MS', 'ZPOT_SHOW_DEV_TOOLS'];
const out = `// AUTO-GENERATED by scripts/gen-env.js from ${path.basename(envFile)} — do not edit.\nexport const GENERATED_ENV: Record<string, string> = ${JSON.stringify(
  Object.fromEntries(keys.map(k => [k, vars[k] ?? ''])), null, 2)};\n`;
fs.writeFileSync(path.join(root, 'src/constants/env.generated.ts'), out);
console.log(`env: wrote src/constants/env.generated.ts from ${path.basename(envFile)}`);
