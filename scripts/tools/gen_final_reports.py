#!/usr/bin/env python3
"""Builds docs/FINAL_SCREEN_COMPLETENESS.md and docs/FINAL_API_COMPLETENESS.md from generated data only:
docs/implementation-status.json (gen_migration_docs.py) and docs/api/endpoint-audit.json (api_audit.py)."""
import json, os
from collections import Counter, defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
st = json.load(open(f"{ROOT}/docs/implementation-status.json"))
au = json.load(open(f"{ROOT}/docs/api/endpoint-audit.json"))
head = "<!-- generated by scripts/tools/gen_final_reports.py; edit the generator or its inputs -->\n"

c = Counter(s["status"] for s in st["screens"])
L = [head, "# Final screen completeness\n",
     f"Source of truth: `docs/implementation-status.json` (commit `{(st['git']['commit'] or '')[:7]}`). "
     f"**{len(st['screens'])} prototype screens**, **{len(st['overlays'])} overlays**, **{st['interactions']['total_bindings']} interaction bindings**.\n",
     "| Status | Screens |\n|---|---|\n" + "\n".join(f"| {k} | {v} |" for k, v in sorted(c.items())) + "\n",
     "| Status | Interaction bindings |\n|---|---|\n" + "\n".join(f"| {k} | {v} |" for k, v in sorted(st["interactions"]["by_status"].items())) + "\n",
     "`partial` and `not-started` are listed below with the reason. `dev-only` bindings are the prototype's simulation panel and are intentionally not shipped. "
     "No prototype button is shipped without an action: screens without an implementation have **no entry point** in the app.\n"]
by = defaultdict(list)
for s in st["screens"]: by[s["module"]].append(s)
for mod, rows in by.items():
    L.append(f"\n## {mod}\n\n| ID | Screen | Status | RN | API | Tests |\n|---|---|---|---|---|---|")
    for s in rows:
        L.append(f"| {s['id']} | {s['name']} | **{s['status']}** | `{s['rn']}` | {'<br>'.join(s['apis']) or '—'} | {s['tests']} |")
L.append("\n## Overlays\n\n| ID | Overlay | Status | RN |\n|---|---|---|---|")
for o in st["overlays"]:
    L.append(f"| {o['id']} | {o['name']} | **{o['status']}** | {o['rn']} |")
open(f"{ROOT}/docs/FINAL_SCREEN_COMPLETENESS.md", "w").write("\n".join(L) + "\n")

s = au["summary"]; n = au["count"]
L = [head, "# Final API completeness\n",
     f"Source: `docs/api/endpoint-audit.json` (from the live drf-spectacular schema). **{n} operations**.\n",
     "| Check | Operations |\n|---|---|",
     f"| Response schema in OpenAPI | {s['response_schema']} / {n} |",
     f"| Exercised by backend tests (`api/tests`) | {s['backend_tests']} / {n} |",
     f"| Documented in `docs/api/endpoints.md` | {s['documented']} / {n} |",
     f"| Called by the mobile service layer | {s['mobile_client']} / {n} |\n",
     "Operations without a mobile client are intentionally server/admin-side (reviewer list, compatibility adapters, devices, etc.) — listed below.\n",
     "| Method | Path | Auth | Tests | Mobile | Docs | Deprecated |\n|---|---|---|---|---|---|---|"]
yn = lambda b: "✓" if b else "—"
for r in au["operations"]:
    L.append(f"| {r['method']} | `{r['path']}` | {r['auth']} | {yn(r['backend_tests'])} | {yn(r['mobile_client'])} | {yn(r['documented'])} | {yn(r['deprecated'])} |")
open(f"{ROOT}/docs/FINAL_API_COMPLETENESS.md", "w").write("\n".join(L) + "\n")
print("screens", dict(c), "| api", s, "of", n)
